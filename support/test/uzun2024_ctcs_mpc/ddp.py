"""Uzun et al. 2024 CTCS NMPC (original 2-D obstacle problem) in ALIPDDP.

Drives the successive synchronous NMPC loop of Algorithm 1 around the C++ horizon
solver ``problem_examples/uzun2024_ctcs_mpc.cpp`` (one process per replan), and
audits every solve and every executed interval independently through
``common.replay_interval`` at 1 ms.  The solver library is not modified.

Per replan i (tc = i * K * dt):
  * measured root = plant state (synchronous: plant time frozen during the solve)
  * sensed mask from the root (common.sensed_mask), frozen for the horizon
  * seed: first solve = zero control rolled out from the root by the solver's own
    discrete map; later solves = previous solution shifted by K intervals, tail
    controls = last interval control, tail states regenerated by the discrete map
    from the shifted last node (paper Sec. 3), seed node 0 = measured root
  * the C++ binary solves ONE horizon: drag double integrator, ZOH controls,
    integrated tracking cost, ||u|| <= umax SOC, and one folded per-interval CTCS
    row I_k/eps - 1 <= 0 over the sensed obstacles (delta-tightened)
  * the first K intervals are applied to the plant with the matching hold (ZOH)
    through common.replay_interval; the end state becomes the next root

ZOH ONLY.  The shared CLI default is FOH (paper eq. 8); this ALIPDDP OCP has no
control-endpoint memory, so ``--hold FOH`` is rejected explicitly with a fail
manifest and exit code 3 rather than silently run as ZOH.

The SCP-only shared flags (--penalty, --prox, --iterations) are accepted for CLI
parity and recorded as unused; ALIPDDP iterates to its own termination, capped by
--ddp-max-iter. See README.md. ``--replay-saved CAMPAIGN`` compares legacy
and shared flow caches on the exact saved retained-MPC request sequence.
"""
