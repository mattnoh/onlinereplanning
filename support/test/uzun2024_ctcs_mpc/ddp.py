class SolverSession:
    """Reuse the CLI process; the restored native binary initializes each solve afresh."""
    def __init__(self, binary, out):
        self.stderr = (out / "server_stderr.txt").open("w")
        self.process = subprocess.Popen([str(binary), "--serve"], stdin=subprocess.PIPE,
            stdout=subprocess.PIPE, stderr=self.stderr, bufsize=0)

    def solve(self, arguments, timeout):
        request = " ".join(json.dumps(str(v)) for v in arguments) + "\n"
        self.process.stdin.write(request.encode()); self.process.stdin.flush()
        data = b""; deadline = time.monotonic() + timeout
        while True:
            remaining = deadline - time.monotonic()
            if remaining <= 0 or not select.select([self.process.stdout], [], [], remaining)[0]:
                raise subprocess.TimeoutExpired(arguments, timeout, output=data)
            chunk = os.read(self.process.stdout.fileno(), 65536)
            if not chunk:
                raise RuntimeError(f"retained solver exited {self.process.poll()}: {data.decode(errors='replace')}")
            data += chunk
            lines = data.split(b"\n")[:-1]
            for line in lines:
                if line.startswith(b"SERVE_DONE "):
                    return int(line.split()[1]), data.decode(errors="replace")

    def close(self):
        try:
            if self.process.poll() is None:
                self.process.stdin.write(b"QUIT\n"); self.process.stdin.flush()
                self.process.wait(timeout=10)
        except (BrokenPipeError, subprocess.TimeoutExpired):
            self.process.kill(); self.process.wait()
        finally:
            self.process.stdin.close(); self.process.stdout.close(); self.stderr.close()

