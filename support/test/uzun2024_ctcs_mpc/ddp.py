def classify(diag, rec, args):
    """Per-solve status.  'solved' = finite and 'Optimal Solution'.  'Outer Max/Min' is
    accepted only when certified (ALIPDDP CLAUDE.md: ignorable if the trajectory is okay).
    Every other label ('Max Iteration', 'Terminated', ...) is a failure that persists."""
    if diag is None or diag.get("status") in ("exception", "unsupported_hold", "bad_json"):
        return "exception"
    if not diag["diagnostics"]["finite"]:
        return "nonfinite"
    term = diag["solver"]["termination"]
    if term == "Optimal Solution":
        return "solved"
    if term == "Outer Max/Min":
        return "solved_outer_maxmin_certified" if rec.get("certified") else "outer_maxmin_uncertified"
    return "unconverged"


def run(args, out):
    global SESSION
    cfg = provenance(args)
    (out / "config.json").write_text(json.dumps(cfg, indent=2, default=str))
    source_dir = out / "source"
    source_dir.mkdir(exist_ok=True)
    for source in (Path(__file__), Path(common.__file__)):
        (source_dir / source.name).write_bytes(source.read_bytes())
    (source_dir / CPP_SOURCE.name).write_bytes(CPP_SOURCE.read_bytes())
    summary = {"status": "fail", "stage": "startup", "solves_completed": 0,
               "constraint_mode": args.constraint_mode, "interval_budget_enforced": args.constraint_mode == "ctcs"}
    solves, plan_rows, exec_rows = [], [], []
    arrays = {"X": [], "U": [], "guess_X": [], "guess_U": [], "tc": [], "mask": [], "root": []}
    dense = []
    executed = []
    plant = np.asarray(args.x0, float)
    try:
        if not Path(args.binary).exists():
            raise FileNotFoundError(f"ALIPDDP binary not built: {args.binary} (see build_ddp.sh)")
        if args.reuse_solver:
            SESSION = SolverSession(args.binary, out)
        n_int = args.nodes - 1
        dt = args.horizon / n_int
        K = args.mpc_intervals
        if K < 1 or K > n_int:
            raise ValueError("mpc_intervals must be in [1, nodes-1]")
        dt_mpc = K * dt
        tc = 0.0
        i = 0
        prev = None
        while tc < args.duration - 1e-9:
            summary["stage"] = f"solve {i} tc={tc:.6g}"
            root = plant.copy()  # measured root (synchronous: plant frozen during solve)
            mask = np.asarray(common.sensed_mask(root[:2]), bool)
            if prev is None:
                seed_X, seed_U, roll_from = None, np.zeros((n_int, 2)), 0
            else:
                Xp, Up = prev
                seed_U = np.r_[Up[K:], np.repeat(Up[-1:], K, axis=0)]
                # tail rows are placeholders regenerated by the C++ discrete map; node 0 is
                # replaced by the measured root in C++ (which reports the shift)
                seed_X = np.r_[Xp[K:], np.repeat(Xp[-1:], K, axis=0)]
                roll_from = n_int - K
            sdir = out / "solves" / f"solve_{i:03d}"
            rec = {"solve": i, "tc": tc, "root": root.tolist(),
                   "mask": "".join("1" if m else "0" for m in mask), "status": "exception",
                   "solve_dir": str(sdir)}
            diag, traj, seed_used, rc, wall = solve_horizon(args, sdir, root, tc, mask, seed_X, seed_U, roll_from)
            rec.update({"returncode": rc, "wall_seconds": wall})
            if diag is None or traj is None or rc not in (0, 1):
                rec["status"] = classify(diag, rec, args) if diag is not None else "exception"
                rec["error"] = (diag or {}).get("message", f"returncode {rc}, see {sdir}/stderr.txt")
                solves.append(rec)
                raise RuntimeError(f"solve {i}: {rec['status']} ({rec['error']})")
            if i == 0:
                summary["cpp_model_check"] = check_cpp_model(diag, traj)
            X, U = traj_arrays(traj)
            d, s = diag["diagnostics"], diag["solver"]
            rec.update({
                "termination": s["termination"], "used_update_problem": s.get("used_update_problem", False), "solver_iterations": s["iterations"],
                "solver_seconds": s["seconds"], "solver_cpu_seconds": s.get("cpu_seconds"), "solver_cost": s["cost"],
                "primal_error": s["primal_error"], "optimality_error": s["optimality_error"],
                "fddp_gap_error": s["fddp_gap_error"],
                "integrated_cost": d["integrated_cost"], "root_defect_inf": d["root_defect_inf"],
                "model_defect_max": d["max_dynamics_defect_inf"], "ctcs_row_max": d["max_ctcs_row"],
                "modeled_path_max": d["max_modeled_path_constraint"],
                "modeled_nodal_g_masked": d["max_nodal_physical_g_masked"],
                "solver_y_increment_max": d["max_interval_integral"], "max_u_norm": d["max_unorm"],
                "seed_defect_inf": d["seed_defect_inf"], "seed_root_shift_inf": d["seed_root_shift_inf"],
            })
            if not d["finite"]:
                rec["status"] = "nonfinite"
                solves.append(rec)
                raise RuntimeError(f"solve {i}: nonfinite result")
            rows = audit_plan(X, U, traj, tc, dt, mask, args)
            for r in rows:
                r["solve"] = i
            plan_rows += rows
            ms_int = max(r["ms_integral"] for r in rows)
            rec.update({
                "ms_integral_max": ms_int,
                "ms_budget_met": bool(ms_int <= common.theorem14_admissible_budget(args.delta, dt, args.umax)),
                "ms_budget_met_strict": bool(ms_int <= args.epsilon * (1 + 1e-6)),
                "ms_phys_defect_max": max(r["ms_phys_defect_inf"] for r in rows),
                "ms_y_defect_max": max(r["ms_y_defect"] for r in rows),
                "ms_l_defect_max": max(r["ms_l_defect"] for r in rows),
                "ss_integral_max": max(r["ss_integral"] for r in rows),
                "ss_max_physical_excess": max(r["ss_max_physical_excess"] for r in rows),
                "ss_node_drift_max": max(r["ss_node_drift_inf"] for r in rows),
                "u_norm_excess": float(np.max(np.linalg.norm(U, axis=1)) - args.umax),
            })
            rec["defects_ok"] = bool(rec["model_defect_max"] <= args.defect_tol
                                     and rec["root_defect_inf"] <= args.defect_tol
                                     and rec["ms_phys_defect_max"] <= args.defect_tol)
            rec["quadrature_ok"] = bool(rec["ms_y_defect_max"] <= args.defect_tol * args.epsilon
                                        and rec["ms_l_defect_max"] <= args.defect_tol)
            rec["certified"] = bool(rec["defects_ok"] and rec["ms_budget_met"]
                                    and rec["ss_max_physical_excess"] <= args.excess_tol
                                    and rec["u_norm_excess"] <= 1e-8)
            if args.constraint_mode == "stage":
                rec["certified"] = bool(rec["defects_ok"] and d["max_modeled_path_constraint"] <= args.ddp_tol
                                        and rec["u_norm_excess"] <= args.ddp_tol)
            rec["status"] = classify(diag, rec, args)

            # Match production's primal acceptance: stationarity is diagnostic,
            # but an infeasible returned plan must not be applied as a new policy.
            primal_error = max(d["max_dynamics_defect_inf"], d["root_defect_inf"],
                max(0., d["max_unorm_excess"]), max(0., d["max_modeled_path_constraint"]))
            rec["returned_primal_error"] = primal_error
            if primal_error > args.ddp_tol:
                rec["status"] = "primal_infeasible"
                solves.append(rec)
                for key, val in (("X", X), ("U", U), ("tc", tc), ("mask", mask), ("root", root)):
                    arrays[key].append(val)
                summary["first_primal_failed_solve"] = i
                raise RuntimeError(f"solve {i}: returned primal {primal_error:.6g} exceeds {args.ddp_tol:g}")

            # Apply first K intervals to the plant with the matching hold (ZOH).
            summary["stage"] = f"evolve {i}"
            for k in range(K):
                if tc + k * dt >= args.duration - 1e-9:
                    break
                applied_dt = min(dt, args.duration - (tc + k * dt))
                rep = replay(plant, U[k], tc + k * dt, applied_dt, mask, args)
                end = np.asarray(rep["end"], float)
                exec_rows.append({
                    "solve": i, "k": k, "t0": tc + k * dt, "duration": applied_dt,
                    "u0": float(U[k][0]), "u1": float(U[k][1]),
                    "integral": float(rep["integral"]), "cost": float(rep["cost"]),
                    "budget_met": bool(rep["integral"] <= common.theorem14_admissible_budget(args.delta, applied_dt, args.umax)),
                    "budget_met_strict": bool(rep["integral"] <= args.epsilon * (1 + 1e-6)),
                    "max_physical_excess": float(rep["max_physical_excess"]),
                    "node_start_g_max": float(np.max(common.obstacle_g(rep["start"][:2]))),
                    "node_end_g_max": float(np.max(common.obstacle_g(end[:2]))),
                    "max_g": float(rep["max_g"]), "max_g_obstacle": int(rep["max_g_obstacle"]),
                    "violation_duration": float(rep["violation_duration"]),
                    "min_clearance": float(rep["min_clearance"]),
                    "min_geometric_clearance": float(rep["min_geometric_clearance"]),
                    "predicted_minus_plant_inf": float(np.max(abs(X[k + 1] - end))),
                    "solver_y_increment": float(traj["I_k"][k]),
                    **{f"x_end_{j}": float(v) for j, v in enumerate(end)},
                })
                dense.append(dense_fields(rep))
                executed.append(rep)
                plant = end
            ex = exec_rows[-K:]
            rec["executed_max_physical_excess"] = max(r["max_physical_excess"] for r in ex)
            rec["executed_integral_max"] = max(r["integral"] for r in ex)
            solves.append(rec)
            for key, v in (("X", X), ("U", U), ("guess_X", seed_used[0]), ("guess_U", seed_used[1]),
                           ("tc", tc), ("mask", mask), ("root", root)):
                arrays[key].append(v)
            summary["solves_completed"] = i + 1
            print(f"[solve {i:2d}] tc={tc:6.2f} mask={rec['mask']} {rec['status']} "
                  f"term='{rec['termination']}' it={rec['solver_iterations']} J={rec['integrated_cost']:.4g} "
                  f"path={rec['modeled_path_max']:.2e} "
                  f"defect={rec['model_defect_max']:.2e} ms_int={ms_int:.2e} "
                  f"exec_excess={rec['executed_max_physical_excess']:.3e} cert={rec['certified']} "
                  f"{rec['solver_seconds']:.2f}s", flush=True)
            if args.stop_on_fail and rec["status"] not in GOOD_STATUS:
                summary["stopped_on_fail"] = i
                raise RuntimeError(f"solve {i}: {rec['status']} (--stop-on-fail)")
            prev = (X, U)
            i += 1
            tc = i * dt_mpc
        summary["stage"] = "done"
    except Exception:
        (out / "error.txt").write_text(traceback.format_exc())
        summary["error"] = traceback.format_exc().splitlines()[-1]
    finally:
        if SESSION is not None:
            SESSION.close(); SESSION = None
        write_csv(out / "solves.csv", solves)
        write_csv(out / "plan_intervals.csv", plan_rows)
        write_csv(out / "executed_intervals.csv", exec_rows)
        np.savez_compressed(out / "arrays.npz", **{k: np.asarray(v) for k, v in arrays.items() if v})
        if dense:
            try:
                np.savez_compressed(out / "closed_loop_dense.npz",
                                    **{k: np.concatenate([np.atleast_1d(d[k]) for d in dense])
                                       for k in dense[0]})
            except Exception as e:  # noqa: BLE001
                summary["dense_save_error"] = repr(e)
        closed = {
            "common_summarize": common.summarize(executed),
            "max_executed_node_g": max((max(r["node_start_g_max"], r["node_end_g_max"]) for r in exec_rows), default=None),
            "executed_intervals": len(exec_rows),
            "max_physical_excess": max((r["max_physical_excess"] for r in exec_rows), default=None),
            "violation_duration_total": sum(r["violation_duration"] for r in exec_rows),
            "min_clearance": min((r["min_clearance"] for r in exec_rows), default=None),
            "max_interval_integral": max((r["integral"] for r in exec_rows), default=None),
            "interval_budgets_met": all(r["budget_met"] for r in exec_rows) if exec_rows else False,
            "interval_budgets_met_strict": all(r["budget_met_strict"] for r in exec_rows) if exec_rows else False,
            "theorem14_admissible_budget": common.theorem14_admissible_budget(args.delta, dt, args.umax),
            "max_predicted_minus_plant": max((r["predicted_minus_plant_inf"] for r in exec_rows), default=None),
            "tracking_cost_sum": sum(r["cost"] for r in exec_rows),
            "final_state": plant.tolist(),
        }
        summary["closed_loop"] = closed
        good = GOOD_STATUS
        summary["solves_converged"] = sum(s.get("status") == "solved" for s in solves)
        summary["solves_certified"] = sum(bool(s.get("certified")) for s in solves)
        summary["first_failed_solve"] = next((s["solve"] for s in solves if s.get("status") not in good), None)
        summary["first_unconverged_solve"] = next(
            (s["solve"] for s in solves if s.get("termination") != "Optimal Solution"), None)
        summary["first_uncertified_solve"] = next((s["solve"] for s in solves if not s.get("certified")), None)
        summary["first_physical_violation_solve"] = next(
            (r["solve"] for r in exec_rows if r["max_physical_excess"] > args.excess_tol), None)
        metrics = closed["common_summarize"]
        summary["physical_execution_pass"] = bool(exec_rows and closed["max_physical_excess"] <= args.excess_tol
            and metrics.get("max_control_norm", float("inf")) <= args.umax + 1e-6)
        summary["useful_tracking_pass"] = bool(exec_rows and metrics.get("mean_tracking_error", float("inf")) <= args.tracking_tol)
        summary["solver_termination_gate_pass"] = all(s.get("status") in good for s in solves)
        ok = (summary["stage"] == "done" and bool(exec_rows)
              and summary["physical_execution_pass"] and summary["useful_tracking_pass"]
              and (args.constraint_mode == "stage" or closed["interval_budgets_met"]))
        summary["status"] = "pass" if ok else "fail"
        summary["pass_definition"] = ("Complete synchronous execution, finite returned plans, physical/input limits, "
            "executed interval budgets (Theorem-14 admissible budget; strict I_k<=epsilon reported separately) when CTCS is enforced, and mean tracking error <= tracking_tol. Solver termination and "
            "future plan feasibility are separate diagnostics, not a perfect optimality requirement.")
        (out / "summary.json").write_text(json.dumps(summary, indent=2, default=str))
        print("DDP_SUMMARY " + json.dumps({k: summary.get(k) for k in
              ("status", "stage", "solves_completed", "solves_converged", "solves_certified",
               "first_failed_solve", "first_uncertified_solve", "first_physical_violation_solve")}
              | {"closed_loop": closed}, default=str), flush=True)
    return summary


def replay_saved(args, out):
    """Paired cache benchmark on a complete saved retained-MPC request sequence.

    Solve sequentially, alternating pair order, with independent retained
    solvers. Reuse the original measured roots and shifted seeds verbatim.
    Full trajectory parity transfers the existing independent plant audits.
    With --replay-inner only the candidate must match its saved campaign;
    baseline/candidate must both pass convergence and independent fine checks.
    No newly integrated plant or real-time performance claim is made here.
    """
    source = args.replay_saved.resolve()
    source_summary = json.loads((source / "summary.json").read_text())
    commands = sorted((source / "solves").glob("solve_*/command.txt"))
    if not commands:
        raise ValueError(f"no saved MPC requests under {source}")
    (out / "config.json").write_text(json.dumps(provenance(args), indent=2, default=str))
    profiles = {"legacy": {"--flow-cache": "legacy"}, "shared": {"--flow-cache": "shared"}}
    if args.replay_inner is not None:
        profiles = {"baseline": {"--inner-tol": "10"},
                    "candidate": {"--inner-tol": str(args.replay_inner)}}
    modes = list(profiles)
    rows, sessions, failure = [], {}, None
    try:
        for mode in modes:
            d = out / mode
            d.mkdir()
            sessions[mode] = SolverSession(args.binary, d)
        for i, saved in enumerate(commands):
            reference = np.genfromtxt(saved.parent / "traj.csv", delimiter=",", names=True)
            orig_diag = json.loads((saved.parent / "diag.json").read_text())
            order = modes if i % 2 == 0 else modes[::-1]
            for mode in order:
                d = out / mode / saved.parent.name
                d.mkdir()
                cmd = shlex.split(saved.read_text())[1:]
                def option(flag, value):
                    if flag in cmd:
                        cmd[cmd.index(flag) + 1] = str(value)
                    else:
                        cmd.extend([flag, str(value)])
                for flag, value in profiles[mode].items():
                    option(flag, value)
                for flag, filename in (("--out-traj", "traj.csv"), ("--out-json", "diag.json"),
                                       ("--out-seed", "seed_used.csv")):
                    option(flag, (d / filename).resolve())
                (d / "request.json").write_text(json.dumps(cmd, indent=2))
                rc, stdout = sessions[mode].solve(cmd, args.solve_timeout)
                (d / "stdout.txt").write_text(stdout)
                diag = json.loads((d / "diag.json").read_text())
                actual = np.genfromtxt(d / "traj.csv", delimiter=",", names=True)
                if reference.dtype.names != actual.dtype.names or reference.shape != actual.shape:
                    raise RuntimeError(f"{mode} {i}: trajectory schema changed")
                ref = np.column_stack([reference[n] for n in reference.dtype.names])
                got = np.column_stack([actual[n] for n in actual.dtype.names])
                same_nan = np.array_equal(np.isnan(ref), np.isnan(got))
                finite = np.isfinite(ref) & np.isfinite(got)
                difference = float(np.max(abs(ref[finite] - got[finite])))
                solver = diag["solver"]
                parity = (same_nan and difference <= 1e-8
                          and solver["iterations"] == orig_diag["solver"]["iterations"]
                          and solver["termination"] == orig_diag["solver"]["termination"])
                d = diag["diagnostics"]
                fine_g = d.get("fine_max_g_masked")
                accepted = (rc == 0 and solver["termination"] == "Optimal Solution"
                    and solver["optimality_error"] <= args.ddp_tol
                    and solver["primal_error"] <= args.defect_tol
                    and d["max_dynamics_defect_inf"] <= args.defect_tol
                    and d["root_defect_inf"] <= args.defect_tol
                    and d["max_unorm_excess"] <= args.excess_tol
                    and (fine_g is None or fine_g <= args.excess_tol)
                    and d["fine_max_interval_integral"] <= d["interval_budget"] * (1 + 1e-6))
                rows.append({"solve": i, "mode": mode, "returncode": rc,
                    "convergence_and_feasibility_pass": accepted,
                    "solver_seconds": solver["seconds"], "solver_cpu_seconds": solver.get("cpu_seconds"),
                    "iterations": solver["iterations"], "termination": solver["termination"],
                    "used_update_problem": solver["used_update_problem"],
                    "trajectory_max_abs_diff": difference, "reference_parity": parity})
                require_parity = args.replay_inner is None or mode == "candidate"
                if not accepted or (require_parity and not parity):
                    raise RuntimeError(f"{mode} solve{i}: failed convergence/feasibility or required saved parity")
            print(f"replay pair {i}: converged/feasible; required saved-reference parity passed", flush=True)
    except Exception:
        failure = traceback.format_exc()
        (out / "error.txt").write_text(failure)
    finally:
        for session in sessions.values():
            session.close()
        write_csv(out / "solves.csv", rows)
    stats = {}
    for mode in modes:
        rr = sorted([r for r in rows if r["mode"] == mode], key=lambda r: r["solve"])
        stats[mode] = {}
        for key in ("solver_seconds", "solver_cpu_seconds"):
            v = np.array([r[key] for r in rr[1:] if r[key] is not None], float)
            if v.size:
                stats[mode][key] = {"median": float(np.median(v)), "p95": float(np.percentile(v, 95)),
                                    "max": float(v.max()), "total_all": sum(r[key] for r in rr)}
    ratios = {key: stats[modes[0]][key]["median"] / stats[modes[1]][key]["median"]
              for key in ("solver_seconds", "solver_cpu_seconds")
              if key in stats[modes[0]] and key in stats[modes[1]]}
    summary = {"status": "pass" if failure is None and len(rows) == 2 * len(commands) else "fail",
        "mode": "saved_retained_mpc_cache_replay" if args.replay_inner is None else "saved_retained_mpc_inner_comparison",
        "profiles": profiles, "source": str(source), "requests": len(commands),
        "all_trajectories_and_iterations_match": all(r["reference_parity"] for r in rows),
        "source_status": source_summary.get("status"),
        "source_physical_execution_pass": source_summary.get("physical_execution_pass"),
        "source_integral_budgets_met": source_summary.get("closed_loop", {}).get("interval_budgets_met"),
        "source_summary_sha256": sha(source / "summary.json"),
        "source_dense_sha256": sha(source / "closed_loop_dense.npz"),
        "audits_transferred_by_trajectory_parity": failure is None and all(r["reference_parity"] for r in rows),
        "max_trajectory_difference": max((r["trajectory_max_abs_diff"] for r in rows), default=None),
        "timing_excludes_first_solve_and_independent_audits": True,
        "timing": stats,
        ("median_speedup_legacy_over_shared" if args.replay_inner is None else "median_speedup_baseline_over_candidate"): ratios}
    (out / "summary.json").write_text(json.dumps(summary, indent=2))
    print("CACHE_REPLAY " + json.dumps(summary), flush=True)
    return summary


def parse(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--output-dir", required=True, type=Path)
    ap.add_argument("--constraint-mode", choices=["ctcs", "stage"], default="ctcs",
                    help="CTCS interval integral or ordinary nodal path constraints including terminal node")
    ap.add_argument("--horizon", type=float, default=8.)
    ap.add_argument("--nodes", type=int, default=17)
    ap.add_argument("--mpc-intervals", type=int, default=4, help="K intervals applied per solve")
    ap.add_argument("--duration", type=float, default=30.)
    ap.add_argument("--hold", type=str.upper, choices=["FOH", "ZOH"], default="ZOH",
                    help="ZOH only; FOH is rejected (exit 3)")
    ap.add_argument("--epsilon", type=float, default=1e-6)
    ap.add_argument("--delta", type=float, default=.05)
    ap.add_argument("--x0", type=float, nargs=4, default=[-10., 0., 0., 0.])
    ap.add_argument("--penalty", type=float, default=1e4, help="SCP only; recorded, unused")
    ap.add_argument("--prox", type=float, default=1., help="SCP only; recorded, unused")
    ap.add_argument("--iterations", type=int, default=3, help="SCP only; recorded, unused")
    ap.add_argument("--umax", type=float, default=5.)
    ap.add_argument("--audit-step", type=float, default=1e-3)
    ap.add_argument("--defect-tol", type=float, default=1e-6)
    ap.add_argument("--excess-tol", type=float, default=1e-6)
    ap.add_argument("--tracking-tol", type=float, default=1.)
    ap.add_argument("--reuse-solver", action="store_true", help="reuse the CLI process; the restored native binary initializes fresh numerical state for every horizon")
    ap.add_argument("--binary", type=Path, default=DEFAULT_BINARY)
    ap.add_argument("--replay-inner", type=float, help="with --replay-saved, compare inner tolerance 10 versus this value; saved campaign must use the candidate setting")
    ap.add_argument("--replay-saved", type=Path, help="paired legacy/shared cache replay of saved retained MPC requests; no plant re-integration")
    ap.add_argument("--flow-cache", choices=["legacy", "shared"], default="legacy",
                    help="exact per-stage dynamics/cost flow reuse; legacy preserves the reference cache layout")
    ap.add_argument("--substeps", type=int, default=100, help="RK4 substeps per interval (assumption)")
    ap.add_argument("--shooting", choices=["ms", "ss"], default="ms")
    ap.add_argument("--cost-hessian", choices=["gn", "fd"], default="gn")
    ap.add_argument("--ddp-max-iter", type=int, default=300)
    ap.add_argument("--ddp-tol", type=float, default=1e-6)
    ap.add_argument("--solve-timeout", type=float, default=600.)
    ap.add_argument("--solver-arg", action="append", default=[],
                    help="extra raw argument passed to the C++ binary (repeatable, e.g. --solver-arg=--mu "
                         "--solver-arg=0.1)")
    ap.add_argument("--stop-on-fail", action="store_true",
                    help="stop at the first failed solve (artifacts are kept either way)")
    args = ap.parse_args(argv)
    if args.replay_inner is not None and (args.replay_saved is None
            or not np.isfinite(args.replay_inner) or args.replay_inner <= 0):
        ap.error("--replay-inner requires --replay-saved and a positive finite value")
    return args


def main(argv=None):
    args = parse(argv)
    out = args.output_dir
    if out.exists() and any(out.iterdir()):
        sys.exit(f"output dir {out} exists and is not empty")
    out.mkdir(parents=True, exist_ok=True)
    if args.replay_saved is not None:
        summary = replay_saved(args, out)
        sys.exit(0 if summary["status"] == "pass" else 1)
    if args.hold != "ZOH":
        msg = ("hold FOH unsupported by the ALIPDDP OCP (no control-endpoint memory); "
               "rerun with --hold ZOH. Not emulated.")
        (out / "summary.json").write_text(json.dumps(
            {"status": "fail", "stage": "config", "error": msg, "hold": args.hold}, indent=2))
        print("DDP_SUMMARY " + json.dumps({"status": "fail", "error": msg}), flush=True)
        sys.exit(3)
    summary = run(args, out)
    sys.exit(0 if summary["status"] == "pass" else 1)


if __name__ == "__main__":
    main()
