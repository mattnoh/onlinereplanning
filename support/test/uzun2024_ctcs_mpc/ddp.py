def replay(x, u, t0, dt, mask, args):
    return common.replay_interval(np.asarray(x, float), np.asarray(u, float), np.asarray(u, float),
                                  float(t0), float(dt), "ZOH", np.asarray(mask, bool),
                                  delta=args.delta, step=args.audit_step)


def audit_plan(X, U, traj, tc, dt, mask, args):
    """Multiple-shooting (node-wise) and single-shooting audit of one horizon plan."""
    rows = []
    state = X[0].copy()
    for k in range(len(U)):
        ms = replay(X[k], U[k], tc + k * dt, dt, mask, args)
        ss = replay(state, U[k], tc + k * dt, dt, mask, args)
        state = np.asarray(ss["end"], float)
        rows.append({
            "k": k, "t0": tc + k * dt,
            "solver_y_increment": float(traj["I_k"][k]),
            "solver_l_increment": float(traj["interval_cost"][k]),
            "solver_ctcs_row": float(traj["ctcs_row"][k]),
            "solver_model_defect_inf": float(traj["defect_inf"][k]),
            "ms_integral": float(ms["integral"]), "ms_cost": float(ms["cost"]),
            "ms_phys_defect_inf": float(np.max(abs(np.asarray(ms["end"]) - X[k + 1]))),
            "ms_y_defect": float(abs(traj["I_k"][k] - ms["integral"])),
            "ms_l_defect": float(abs(traj["interval_cost"][k] - ms["cost"])),
            "ms_max_physical_excess": float(ms["max_physical_excess"]),
            "ms_violation_duration": float(ms["violation_duration"]),
            "ss_integral": float(ss["integral"]),
            "ss_max_physical_excess": float(ss["max_physical_excess"]),
            "ss_violation_duration": float(ss["violation_duration"]),
            "ss_node_drift_inf": float(np.max(abs(state - X[k + 1]))),
        })
    return rows


def dense_fields(rep):
    return {k: np.asarray(v) for k, v in rep.items()
            if k in ("times", "states", "controls", "g")}


