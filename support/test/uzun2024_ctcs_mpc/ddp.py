def sha(p):
    p = Path(p)
    return hashlib.sha256(p.read_bytes()).hexdigest() if p.exists() else None


def git_rev(path):
    try:
        rev = subprocess.check_output(["git", "-C", str(path), "rev-parse", "HEAD"], text=True).strip()
        dirty = subprocess.check_output(["git", "-C", str(path), "status", "--porcelain",
                                         str(CPP_SOURCE.relative_to(ALIPDDP_ROOT))], text=True).strip()
        return rev, dirty
    except Exception as e:  # noqa: BLE001
        return f"unavailable: {e}", None


def write_csv(path, rows):
    if not rows:
        path.write_text("")
        return
    fields = list(dict.fromkeys(k for r in rows for k in r))
    with path.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(rows)


def write_rows(path, arr):
    np.savetxt(path, np.asarray(arr, float), delimiter=",", fmt="%.17g")


