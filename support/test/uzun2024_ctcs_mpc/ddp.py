def solve_horizon(args, sdir, root, tc, mask, seed_X, seed_U, roll_from):
    """Run one ALIPDDP horizon solve.  Returns (diag json, traj, (seed X, seed U), returncode, wall s)."""
    sdir.mkdir(parents=True, exist_ok=True)
    cmd = [str(args.binary), "--x0", ",".join(f"{v:.17g}" for v in root), "--epoch", f"{tc:.17g}",
           "--mask", ",".join("1" if m else "0" for m in mask),
           "--N", str(args.nodes - 1), "--dt", f"{args.horizon / (args.nodes - 1):.17g}",
           "--substeps", str(args.substeps), "--eps", f"{args.epsilon:.17g}",
           "--delta", f"{args.delta:.17g}", "--umax", f"{args.umax:.17g}", "--cd", f"{common.C_D:.17g}",
           "--constraint-mode", args.constraint_mode, "--flow-cache", args.flow_cache,
           "--hold", "zoh", "--shooting", args.shooting, "--cost-hessian", args.cost_hessian,
           "--max-iter", str(args.ddp_max_iter), "--tol", f"{args.ddp_tol:.17g}",
           "--audit-step", f"{args.audit_step:.17g}",
           "--out-traj", str(sdir / "traj.csv"), "--out-json", str(sdir / "diag.json"),
           "--out-seed", str(sdir / "seed_used.csv")]
    if seed_U is not None:
        write_rows(sdir / "seed_u.csv", seed_U)
        cmd += ["--seed-u", str(sdir / "seed_u.csv")]
    if seed_X is not None:
        write_rows(sdir / "seed_x.csv", seed_X)
        cmd += ["--seed-x", str(sdir / "seed_x.csv"), "--seed-rollout-from", str(roll_from)]
    cmd += args.solver_arg
    (sdir / "command.txt").write_text(" ".join(cmd) + "\n")
    t0 = time.perf_counter()
    try:
        if SESSION is None:
            proc = subprocess.run(cmd, capture_output=True, text=True, timeout=args.solve_timeout)
            rc, out, err = proc.returncode, proc.stdout, proc.stderr
        else:
            rc, out = SESSION.solve(cmd[1:], args.solve_timeout)
            err = ""
    except subprocess.TimeoutExpired as e:
        rc, out, err = "timeout", e.stdout or "", e.stderr or ""
    wall = time.perf_counter() - t0
    (sdir / "stdout.txt").write_text(out if isinstance(out, str) else out.decode(errors="replace"))
    (sdir / "stderr.txt").write_text(err if isinstance(err, str) else err.decode(errors="replace"))
    diag = None
    if (sdir / "diag.json").exists():
        try:
            diag = json.loads((sdir / "diag.json").read_text())
        except json.JSONDecodeError as e:
            diag = {"status": "bad_json", "message": repr(e)}
    traj = seed = None
    if (sdir / "traj.csv").exists() and rc in (0, 1):
        traj = np.genfromtxt(sdir / "traj.csv", delimiter=",", names=True)
    if (sdir / "seed_used.csv").exists():
        sd = np.genfromtxt(sdir / "seed_used.csv", delimiter=",", names=True)
        seed = (np.c_[sd["rx"], sd["ry"], sd["vx"], sd["vy"]], np.c_[sd["ux"], sd["uy"]][:-1])
    return diag, traj, seed, rc, wall


def traj_arrays(traj):
    X = np.c_[traj["rx"], traj["ry"], traj["vx"], traj["vy"]]
    U = np.c_[traj["ux"], traj["uy"]][:-1]
    return X, U


def check_cpp_model(diag, traj):
    """The C++ OCP must carry exactly common.py's constants and reference."""
    cfg = diag["config"]
    errs = {
        "S_diag": float(np.max(abs(np.asarray(cfg["S_diag"]) - common.SHAPE_DIAG))),
        "centers": float(np.max(abs(np.c_[cfg["obstacle_cx"], cfg["obstacle_cy"]] - common.CENTERS))),
        "cd": abs(cfg["cd"] - common.C_D),
        "reference": float(np.max(abs(np.c_[traj["rref_x"], traj["rref_y"]]
                                      - common.reference(traj["t_abs"])))),
    }
    bad = {k: v for k, v in errs.items() if not v <= 1e-12}
    if bad:
        raise RuntimeError(f"C++ OCP disagrees with common.py: {errs}")
    return errs


